#!/usr/bin/env python3
"""
Extract the trained LSTM weights into a TypeScript module the Next.js API routes
can import directly.

The dashboard runs inference in pure TypeScript (see src/lib/model/lstm.ts), so
Python is a *development-only* dependency: run this script whenever the trained
model changes, commit the generated file, and deploys need nothing but Node.

Also emits golden fixtures — real (sequence -> probability) pairs produced by
Keras itself — so scripts/verify-model-parity.mjs can prove the TypeScript port
still matches the original model.

Usage:
    python3 -m venv .venv
    .venv/bin/pip install keras jax h5py numpy scipy
    .venv/bin/python scripts/extract-model-weights.py
"""

from __future__ import annotations

import base64
import json
import os
from pathlib import Path

os.environ.setdefault("KERAS_BACKEND", "jax")

import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MODEL_PATH = ROOT / "model" / "predictive_maintenance_model.keras"
WEIGHTS_OUT = ROOT / "src" / "lib" / "model" / "weights.ts"
GOLDEN_OUT = ROOT / "src" / "lib" / "model" / "golden-fixtures.json"
X_PATH = ROOT / "data" / "X_processed.npy"

SEQUENCE_LENGTH = 50
FEATURE_COUNT = 7
GOLDEN_SAMPLES = 24


def b64(array: np.ndarray) -> str:
    """Little-endian float32 bytes, base64 encoded."""
    return base64.b64encode(np.ascontiguousarray(array, dtype="<f4").tobytes()).decode("ascii")


def main() -> None:
    import keras

    model = keras.saving.load_model(MODEL_PATH, compile=False)
    lstm, dense = model.get_layer("lstm"), model.get_layer("dense")

    kernel, recurrent_kernel, bias = (np.asarray(w) for w in lstm.get_weights())
    dense_kernel, dense_bias = (np.asarray(w) for w in dense.get_weights())

    units = int(lstm.units)
    assert kernel.shape == (FEATURE_COUNT, 4 * units), kernel.shape
    assert recurrent_kernel.shape == (units, 4 * units), recurrent_kernel.shape
    assert bias.shape == (4 * units,), bias.shape
    assert dense_kernel.shape == (units, 1), dense_kernel.shape

    header = (
        "// GENERATED FILE — do not edit by hand.\n"
        "// Produced by scripts/extract-model-weights.py from\n"
        "// model/predictive_maintenance_model.keras\n"
        "//\n"
        "// Weights are little-endian float32, base64 encoded. Keras packs the four\n"
        "// LSTM gates along the last axis in the order [input, forget, cell, output].\n\n"
    )

    body = f"""export const MODEL_SHAPE = {{
  sequenceLength: {SEQUENCE_LENGTH},
  featureCount: {FEATURE_COUNT},
  units: {units},
}} as const;

/** LSTM input kernel — shape ({FEATURE_COUNT}, {4 * units}), row-major. */
export const LSTM_KERNEL_B64 =
  "{b64(kernel)}";

/** LSTM recurrent kernel — shape ({units}, {4 * units}), row-major. */
export const LSTM_RECURRENT_KERNEL_B64 =
  "{b64(recurrent_kernel)}";

/** LSTM bias — shape ({4 * units},). */
export const LSTM_BIAS_B64 =
  "{b64(bias)}";

/** Dense kernel — shape ({units}, 1). */
export const DENSE_KERNEL_B64 =
  "{b64(dense_kernel)}";

/** Dense bias — shape (1,). */
export const DENSE_BIAS_B64 =
  "{b64(dense_bias)}";
"""

    WEIGHTS_OUT.parent.mkdir(parents=True, exist_ok=True)
    WEIGHTS_OUT.write_text(header + body, encoding="utf-8")
    print(f"wrote {WEIGHTS_OUT.relative_to(ROOT)} ({WEIGHTS_OUT.stat().st_size:,} bytes)")

    # --- golden fixtures -----------------------------------------------------
    X = np.load(X_PATH, allow_pickle=True).astype("float32")
    rng = np.random.default_rng(seed=20260720)

    starts = rng.choice(len(X) - SEQUENCE_LENGTH, size=GOLDEN_SAMPLES, replace=False)
    windows = np.stack([X[s : s + SEQUENCE_LENGTH] for s in starts]).astype("float32")

    # A few synthetic extremes so the fixtures cover the saturating tails too.
    extremes = np.stack([
        np.zeros((SEQUENCE_LENGTH, FEATURE_COUNT), dtype="float32"),
        np.full((SEQUENCE_LENGTH, FEATURE_COUNT), 3.0, dtype="float32"),
        np.full((SEQUENCE_LENGTH, FEATURE_COUNT), -3.0, dtype="float32"),
        rng.normal(0, 1, (SEQUENCE_LENGTH, FEATURE_COUNT)).astype("float32"),
    ])

    batch = np.concatenate([windows, extremes], axis=0)
    probabilities = model.predict(batch, verbose=0).reshape(-1)

    fixtures = {
        "note": (
            "Generated by scripts/extract-model-weights.py using Keras itself. "
            "scripts/verify-model-parity.mjs replays these through the TypeScript "
            "implementation and asserts the probabilities still match."
        ),
        "sequenceLength": SEQUENCE_LENGTH,
        "featureCount": FEATURE_COUNT,
        "cases": [
            {
                "sequence": [[round(float(v), 7) for v in step] for step in seq],
                "expectedProbability": float(p),
            }
            for seq, p in zip(batch, probabilities)
        ],
    }

    GOLDEN_OUT.write_text(json.dumps(fixtures), encoding="utf-8")
    print(f"wrote {GOLDEN_OUT.relative_to(ROOT)} ({GOLDEN_OUT.stat().st_size:,} bytes, {len(fixtures['cases'])} cases)")
    print(f"probability range: {probabilities.min():.6f} .. {probabilities.max():.6f}")


if __name__ == "__main__":
    main()
